-- Flower Lantern Spa — PostgreSQL schema (Neon). Consolidated, behaviour-equivalent port of the SQL Server
-- migrations 001-008 (database/migrations/*.sql, kept unchanged for rollback; tag sqlserver-baseline).
--
-- Conventions
--  * Schema "dbo" and UNQUOTED identifiers: PostgreSQL folds them to lowercase, so the application's existing
--    PascalCase references (dbo.LichHen.MaLichHen) resolve unchanged. Result columns come back lowercase unless
--    the query aliases them with a quoted identifier.
--  * Type mapping: CHAR(n)->char(n) (same blank-padded semantics), NVARCHAR(n)->varchar(n) (UTF-8 database),
--    NVARCHAR(MAX)->text, DATETIME->timestamp(3), DATETIME2(p)->timestamp(p), MONEY->numeric(19,4),
--    TINYINT->smallint, UNIQUEIDENTIFIER->uuid, BIGINT IDENTITY->bigint GENERATED BY DEFAULT AS IDENTITY.
--  * GETDATE() was Vietnam local time on the original server. dbo.vn_now() reproduces that on a UTC server.
--  * SQL Server's default collation is case-insensitive; the unique service name is enforced on lower(name).
--  * Phone CHECKs: T-SQL "NOT LIKE '%[^0-9]%'" -> POSIX regex '^[0-9]*$'.
-- Idempotent: safe to re-run (IF NOT EXISTS everywhere). Run on the DIRECT (non-pooler) Neon URL.

CREATE SCHEMA IF NOT EXISTS dbo;

CREATE OR REPLACE FUNCTION dbo.vn_now() RETURNS timestamp(3)
  LANGUAGE sql STABLE AS $$ SELECT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh')::timestamp(3) $$;

CREATE OR REPLACE FUNCTION dbo.utc_now() RETURNS timestamp(3)
  LANGUAGE sql STABLE AS $$ SELECT (now() AT TIME ZONE 'UTC')::timestamp(3) $$;

-- ---------------------------------------------------------------- 001 baseline (15 SRS tables)
CREATE TABLE IF NOT EXISTS dbo.TaiKhoan (
  MaTaiKhoan char(10) NOT NULL PRIMARY KEY,
  TenDangNhap varchar(50) NOT NULL UNIQUE,
  SoDienThoai varchar(15) NOT NULL CHECK (SoDienThoai ~ '^[0-9]*$'),
  MatKhauBam varchar(255) NOT NULL,
  VaiTro varchar(30) NOT NULL,
  TrangThai varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS dbo.Quyen (
  MaQuyen char(10) NOT NULL PRIMARY KEY,
  TenQuyen varchar(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS dbo.TaiKhoanQuyen (
  MaTaiKhoan char(10) NOT NULL REFERENCES dbo.TaiKhoan(MaTaiKhoan),
  MaQuyen char(10) NOT NULL REFERENCES dbo.Quyen(MaQuyen),
  PRIMARY KEY (MaTaiKhoan, MaQuyen)
);
CREATE TABLE IF NOT EXISTS dbo.LichSuPhanQuyen (
  MaLichSu char(10) NOT NULL PRIMARY KEY,
  MaTaiKhoanThucHien char(10) NOT NULL REFERENCES dbo.TaiKhoan(MaTaiKhoan),
  MaTaiKhoanDuocPhanQuyen char(10) NOT NULL REFERENCES dbo.TaiKhoan(MaTaiKhoan),
  ThoiDiem timestamp(3) NOT NULL CHECK (ThoiDiem <= dbo.vn_now()),
  NoiDungThayDoi varchar(500) NULL
);
CREATE TABLE IF NOT EXISTS dbo.KhachHang (
  MaKhachHang char(10) NOT NULL PRIMARY KEY,
  MaTaiKhoan char(10) NULL REFERENCES dbo.TaiKhoan(MaTaiKhoan),
  HoTen varchar(50) NOT NULL,
  SoDienThoai char(10) NOT NULL CHECK (SoDienThoai ~ '^[0-9]*$'),
  NgaySinh date NULL CHECK (NgaySinh < dbo.vn_now()::date),
  KenhLienHe varchar(50) NULL,
  GioiTinh varchar(10) NULL,
  DiaChi varchar(255) NULL,
  GhiChu varchar(500) NULL,
  NgayTao timestamp(3) NOT NULL DEFAULT dbo.vn_now()
);
CREATE TABLE IF NOT EXISTS dbo.NhanVien (
  MaNhanVien char(10) NOT NULL PRIMARY KEY,
  MaTaiKhoan char(10) NULL REFERENCES dbo.TaiKhoan(MaTaiKhoan),
  HoTen varchar(50) NOT NULL,
  SoDienThoai char(10) NOT NULL CHECK (SoDienThoai ~ '^[0-9]*$'),
  Email varchar(100) NULL,
  GioiTinh varchar(10) NULL,
  NgaySinh date NULL CHECK (NgaySinh < dbo.vn_now()::date),
  DiaChi varchar(255) NULL,
  GhiChu varchar(500) NULL,
  TrangThaiLamViec varchar(30) NOT NULL,
  TrangThaiHoSo varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS dbo.DanhMuc (
  MaDanhMuc char(10) NOT NULL PRIMARY KEY,
  TenDanhMuc varchar(100) NOT NULL,
  TrangThai varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS dbo.DichVu (
  MaDichVu char(10) NOT NULL PRIMARY KEY,
  MaDanhMuc char(10) NOT NULL REFERENCES dbo.DanhMuc(MaDanhMuc),
  TenDichVu varchar(150) NOT NULL,
  HinhAnh varchar(255) NULL,
  MoTaNgan varchar(255) NULL,
  MoTaChiTiet text NULL,
  LoiIch text NULL,
  QuyTrinhThucHien text NULL,
  DoiTuongPhuHop varchar(255) NULL,
  ThongTinLieuTrinhVaLuuY text NULL,
  TrangThai varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS dbo.GoiDichVu (
  MaGoi char(10) NOT NULL PRIMARY KEY,
  MaDichVu char(10) NOT NULL REFERENCES dbo.DichVu(MaDichVu),
  TenGoi varchar(100) NOT NULL,
  ThoiLuong integer NOT NULL CHECK (ThoiLuong > 0),
  Gia numeric(19,4) NOT NULL CHECK (Gia >= 0),
  -- 005: package can be deactivated instead of deleted when it has history.
  TrangThai varchar(30) NOT NULL DEFAULT 'Hoạt động'
);
CREATE TABLE IF NOT EXISTS dbo.LichHen (
  MaLichHen char(10) NOT NULL PRIMARY KEY,
  MaKhachHang char(10) NULL REFERENCES dbo.KhachHang(MaKhachHang),
  HoTenNguoiDat varchar(50) NOT NULL,
  SoDienThoaiNguoiDat char(10) NOT NULL CHECK (SoDienThoaiNguoiDat ~ '^[0-9]*$'),
  EmailNguoiDat varchar(100) NULL,
  GhiChu varchar(500) NULL,
  NgayHen date NOT NULL,
  GioHen time NOT NULL,
  ThoiGianDat timestamp(3) NOT NULL DEFAULT dbo.vn_now(),
  TrangThaiLichHen varchar(30) NOT NULL,
  TrangThaiThanhToan varchar(30) NOT NULL,
  -- 008: booking source ('ONLINE' for online bookings); NULL = not recorded.
  NguonDatLich varchar(50) NULL
);
CREATE TABLE IF NOT EXISTS dbo.Giuong (MaGiuong char(10) NOT NULL PRIMARY KEY);
CREATE TABLE IF NOT EXISTS dbo.KhachSuDungDichVu (
  MaChiTiet char(10) NOT NULL PRIMARY KEY,
  MaLichHen char(10) NOT NULL REFERENCES dbo.LichHen(MaLichHen),
  MaGoi char(10) NOT NULL REFERENCES dbo.GoiDichVu(MaGoi),
  MaGiuong char(10) NULL REFERENCES dbo.Giuong(MaGiuong),
  TenKhach varchar(50) NOT NULL,
  SoDienThoai char(10) NULL CHECK (SoDienThoai ~ '^[0-9]*$'),
  ThoiDiemBatDau timestamp(3) NOT NULL,
  ThoiDiemKetThuc timestamp(3) NOT NULL,
  CONSTRAINT CK_KhachSuDungDichVu_Interval CHECK (ThoiDiemKetThuc > ThoiDiemBatDau)
);
CREATE TABLE IF NOT EXISTS dbo.ThanhToan (
  MaThanhToan char(10) NOT NULL PRIMARY KEY,
  MaLichHen char(10) NOT NULL REFERENCES dbo.LichHen(MaLichHen),
  SoTienThanhToan numeric(19,4) NOT NULL CHECK (SoTienThanhToan >= 0),
  NgayGhiNhan timestamp(3) NOT NULL CHECK (NgayGhiNhan <= dbo.vn_now()),
  TrangThaiGiaoDich varchar(30) NOT NULL,
  KhoanHoanTien numeric(19,4) NULL DEFAULT 0 CHECK (KhoanHoanTien >= 0),
  -- 007: SePay columns (all nullable; NULL provider = manual/cash entry).
  MaThamChieu varchar(32) NULL,
  NhaCungCap varchar(20) NULL,
  MaGiaoDichNhaCungCap varchar(64) NULL,
  HanThanhToan timestamp(3) NULL,
  SoTaiKhoanNhan varchar(30) NULL
);
CREATE TABLE IF NOT EXISTS dbo.DanhGia (
  MaDanhGia char(10) NOT NULL PRIMARY KEY,
  MaLichHen char(10) NOT NULL REFERENCES dbo.LichHen(MaLichHen),
  MaKhachHang char(10) NOT NULL REFERENCES dbo.KhachHang(MaKhachHang),
  MaDichVu char(10) NOT NULL REFERENCES dbo.DichVu(MaDichVu),
  SoSao smallint NOT NULL CHECK (SoSao BETWEEN 1 AND 5),
  NoiDungDanhGia varchar(1000) NULL,
  NgayDanhGia timestamp(3) NOT NULL DEFAULT dbo.vn_now()
);
CREATE TABLE IF NOT EXISTS dbo.PhanHoi (
  MaPhanHoi char(10) NOT NULL PRIMARY KEY,
  MaDanhGia char(10) NOT NULL REFERENCES dbo.DanhGia(MaDanhGia),
  MaNhanVien char(10) NOT NULL REFERENCES dbo.NhanVien(MaNhanVien),
  NoiDungPhanHoi varchar(1000) NOT NULL,
  -- 006: reply time in UTC; existing replies stay NULL (none invented).
  NgayPhanHoi timestamp(0) NULL DEFAULT dbo.utc_now()
);

-- ---------------------------------------------------------------- 002 business indexes
CREATE UNIQUE INDEX IF NOT EXISTS UX_TaiKhoan_SoDienThoai ON dbo.TaiKhoan(SoDienThoai);
CREATE UNIQUE INDEX IF NOT EXISTS UX_KhachHang_SoDienThoai ON dbo.KhachHang(SoDienThoai);
