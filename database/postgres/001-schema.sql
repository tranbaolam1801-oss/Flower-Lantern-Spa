CREATE UNIQUE INDEX IF NOT EXISTS UX_DanhGia_LichHen ON dbo.DanhGia(MaLichHen);
CREATE UNIQUE INDEX IF NOT EXISTS UX_PhanHoi_DanhGia ON dbo.PhanHoi(MaDanhGia);
